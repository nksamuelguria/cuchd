var delta = 5;
var hh = $('header').outerHeight();
var dh = $(document).height();
var wh = $(window).height();


$(window).scroll(function(event) {
  scrolling = true;
});

setInterval(function() {
  if (scrolling) {
    scrollFunction();
    scrolling = false;
  }
